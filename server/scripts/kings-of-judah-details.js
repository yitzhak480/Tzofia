const main = async () => {
  await mongoose.connect(process.env.MONGO_URI);
  const people = await Person.find({ slug: { $in: Object.keys(KINGS) } });
  const bySlug = new Map(people.map((p) => [p.slug, p]));

  for (const [slug, data] of Object.entries(KINGS)) {
    const person = bySlug.get(slug);
    if (!person) {
      console.log(`✗ ${slug}: not found, skipped`);
      continue;
    }
    const relations = data.relations.map((r) => {
      if (r.slug) {
        const other = bySlug.get(r.slug);
        return { type: r.type, person: other?._id || null, name: { he: other?.name.he || r.slug, en: other?.name.en || '' } };
      }
      return { type: r.type, person: null, name: { he: r.name, en: '' } };
    });
    person.set({
      roles: data.roles.map((he) => ({ he, en: '' })),
      life: data.life ? { from: data.life[0], to: data.life[1] } : { from: null, to: null },
      offices: data.offices,
      relations,
      sources: data.sources,
      treeSpots: data.spot,
      content: { he: data.content, en: person.content?.en || '' },
    });
    await person.save();
    console.log(`✓ ${person.name.he}`);
  }
  await mongoose.disconnect();
};

main().catch(async (err) => {
  console.error(err);
  await mongoose.disconnect();
  process.exit(1);
});
